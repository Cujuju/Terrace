const PROBE_COVERED_FLAG = 1;
const CAMERA_HEIGHT_WORLD = 64;
const CAMERA_NEAR_WORLD = 1;
const CAMERA_FAR_WORLD = 256;
const INSTANCE_COMPONENTS = 2;
const META_ROUTE = '/probe-meta';
const HEIGHTS_ROUTE = '/probe-heights';

const PROBE_PAGE = `<!doctype html><meta charset="utf-8"><title>independent gpu terrain parity</title>
<script type="module" src="/probe.js"></script>`;

const PROBE_SCRIPT = `
import * as THREE from 'three';
import { createChunkTemplate, createGpuTerrainMaterial } from 'gpuTerrainMaterial';
import { createBandPaletteTexture, createHeightTexture } from 'gpuTerrainTextures';

${MAP_BUILDER_SOURCE}

const JOBS = ${JSON.stringify(JOBS)};
const CHUNK_SIZE = ${REF_CHUNK_SIZE};
const CELL_WORLD_SIZE = ${REF_CELL_WORLD_SIZE};
const CELL_CENTRE_OFFSET = ${REF_CELL_CENTRE_OFFSET};
const MIN_HEIGHT = ${REF_MIN_HEIGHT};
const MAX_HEIGHT = ${REF_MAX_HEIGHT};
const BAND_HEIGHT = ${REF_BAND_HEIGHT};
const COVERED_FLAG = ${PROBE_COVERED_FLAG};
const CAMERA_HEIGHT = ${CAMERA_HEIGHT_WORLD};
const CAMERA_NEAR = ${CAMERA_NEAR_WORLD};
const CAMERA_FAR = ${CAMERA_FAR_WORLD};
const INSTANCE_COMPONENTS = ${INSTANCE_COMPONENTS};

const PROBE_VARYING = 'flat varying float vProbeHeight;\\n';
const VERTEX_ANCHOR = '#include <project_vertex>';
const FRAGMENT_ANCHOR = '#include <dithering_fragment>';

/** Each deforms the shipped material so a clean run proves the check bites. */
const MUTATIONS = {
  dropHalfCell: ['(subIJ + 0.5) / uSubdiv', '(subIJ) / uSubdiv'],
  shiftSubcell: ['(subIJ + 0.5) / uSubdiv', '(subIJ + 1.5) / uSubdiv'],
  truncDiv: ['return q * b > a ? q - 1 : q;', 'return q;'],
};

function splice(source, anchor, replacement) {
  if (!source.includes(anchor)) throw new Error('probe anchor missing: ' + anchor);
  return source.replace(anchor, replacement);
}

const errors = [];
window.addEventListener('error', (e) => errors.push(String(e.message)));
window.addEventListener('unhandledrejection', (e) => errors.push(String(e.reason)));

const canvas = document.createElement('canvas');
const renderer = new THREE.WebGLRenderer({ canvas, antialias: false });
renderer.outputColorSpace = THREE.LinearSRGBColorSpace;
renderer.toneMapping = THREE.NoToneMapping;
renderer.setClearColor(0x000000, 1);

function probeMaterial(uniforms, subdiv, mutate) {
  const material = createGpuTerrainMaterial({ ...uniforms, uSubdiv: { value: subdiv } });
  const base = material.onBeforeCompile.bind(material);
  material.onBeforeCompile = (shader, r) => {
    base(shader, r);
    let vs = PROBE_VARYING + shader.vertexShader;
    if (mutate !== null) {
      const [anchor, replacement] = MUTATIONS[mutate];
      if (!vs.includes(anchor)) throw new Error('mutation anchor missing: ' + mutate);
      vs = vs.replace(anchor, replacement);
    }
    shader.vertexShader = splice(vs, VERTEX_ANCHOR, 'vProbeHeight = float(heightHere);\\n  ' + VERTEX_ANCHOR);
    shader.fragmentShader = splice(
      PROBE_VARYING + shader.fragmentShader,
      FRAGMENT_ANCHOR,
      'gl_FragColor = vec4(vProbeHeight, ' + COVERED_FLAG.toFixed(1) + ', 0.0, 1.0);',
    );
  };
  material.customProgramCacheKey = () => 'independent-probe|' + subdiv + '|' + String(mutate);
  return material;
}

const cellCoordToWorld = (c) => (c - CELL_CENTRE_OFFSET) * CELL_WORLD_SIZE;

let loaded = null;

function load(kind, size) {
  if (loaded !== null) loaded.height.dispose();
  const map = {
    size,
    cells: buildMapCells(kind, size, MIN_HEIGHT, MAX_HEIGHT, BAND_HEIGHT),
    columnSpans: new Map(),
  };
  loaded = { key: kind + ':' + size, map, height: createHeightTexture(map) };
  return loaded.map.columnSpans.size;
}

function probe(job) {
  const uniforms = {
    uHeight: { value: loaded.height.texture },
    uPalette: { value: createBandPaletteTexture() },
    uSizeCells: { value: loaded.map.size },
    uSmooth: { value: 1 },
  };
  const { geometry } = createChunkTemplate(job.subdiv);
  const count = job.chunks * job.chunks;
  const origins = new THREE.InstancedBufferAttribute(
    new Float32Array(count * INSTANCE_COMPONENTS),
    INSTANCE_COMPONENTS,
  );
  for (let j = 0; j < job.chunks; j++) {
    for (let i = 0; i < job.chunks; i++) {
      const slot = (j * job.chunks + i) * INSTANCE_COMPONENTS;
      origins.array[slot] = (job.cx0 + i) * CHUNK_SIZE;
      origins.array[slot + 1] = (job.cy0 + j) * CHUNK_SIZE;
    }
  }
  geometry.setAttribute('aChunk', origins);
  geometry.instanceCount = count;

  const material = probeMaterial(uniforms, job.subdiv, job.mutate);
  const mesh = new THREE.Mesh(geometry, material);
  mesh.frustumCulled = false;
  const scene = new THREE.Scene();
  scene.add(mesh);

  const cellSpan = job.chunks * CHUNK_SIZE;
  const side = cellSpan * job.subdiv;
  const half = (cellSpan * CELL_WORLD_SIZE) / 2;
  const centreX = cellCoordToWorld(job.cx0 * CHUNK_SIZE) + half;
  const centreZ = cellCoordToWorld(job.cy0 * CHUNK_SIZE) + half;
  // Top and bottom are swapped so readback row 0 is the low-Z edge.
  const camera = new THREE.OrthographicCamera(-half, half, -half, half, CAMERA_NEAR, CAMERA_FAR);
  camera.position.set(centreX, CAMERA_HEIGHT, centreZ);
  camera.rotation.set(-Math.PI / 2, 0, 0);
  camera.updateMatrixWorld(true);
  camera.updateProjectionMatrix();

  const target = new THREE.WebGLRenderTarget(side, side, {
    format: THREE.RGBAFormat,
    type: THREE.FloatType,
    minFilter: THREE.NearestFilter,
    magFilter: THREE.NearestFilter,
    depthBuffer: true,
    stencilBuffer: false,
  });
  renderer.setRenderTarget(target);
  renderer.clear(true, true, false);
  renderer.render(scene, camera);
  const raw = new Float32Array(side * side * 4);
  renderer.readRenderTargetPixels(target, 0, 0, side, side, raw);
  renderer.setRenderTarget(null);
  target.dispose();
  geometry.dispose();
  material.dispose();
  uniforms.uPalette.value.dispose();

  const heights = new Float32Array(side * side);
  let uncovered = 0;
  for (let i = 0; i < heights.length; i++) {
    if (raw[i * 4 + 1] !== COVERED_FLAG) uncovered++;
    heights[i] = raw[i * 4];
  }
  return { heights, uncovered, side };
}

function rendererName() {
  const gl = renderer.getContext();
  const ext = gl.getExtension('WEBGL_debug_renderer_info');
  return ext ? gl.getParameter(ext.UNMASKED_RENDERER_WEBGL) : gl.getParameter(gl.RENDERER);
}

(async () => {
  const meta = { renderer: '', jobs: [], errors, fatal: null };
  const blocks = [];
  try {
    meta.renderer = rendererName();
    for (const job of JOBS) {
      const key = job.kind + ':' + job.size;
      const layered = loaded !== null && loaded.key === key ? 0 : load(job.kind, job.size);
      if (layered !== 0) throw new Error('layered columns present; this reference covers unlayered only');
      const result = probe(job);
      meta.jobs.push({ label: job.label, side: result.side, uncovered: result.uncovered });
      blocks.push(result.heights);
    }
  } catch (error) {
    meta.fatal = String((error && error.stack) || error);
  }
  let total = 0;
  for (const b of blocks) total += b.length;
  const flat = new Float32Array(total);
  let offset = 0;
  for (const b of blocks) {
    flat.set(b, offset);
    offset += b.length;
  }
  await fetch(${JSON.stringify(META_ROUTE)}, { method: 'POST', body: JSON.stringify(meta) });
  await fetch(${JSON.stringify(HEIGHTS_ROUTE)}, { method: 'POST', body: flat.buffer });
})();
`;

