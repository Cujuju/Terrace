const SMALL_CHUNKS_PER_EDGE = 4;
const SMALL_SIZE = REF_CHUNK_SIZE * SMALL_CHUNKS_PER_EDGE;
const LARGE_SIZE = 2048;
const LARGE_CHUNKS_PER_EDGE = LARGE_SIZE / REF_CHUNK_SIZE;
const WINDOW_CHUNKS = 2;
const LARGE_CORNER_CHUNK0 = LARGE_CHUNKS_PER_EDGE - WINDOW_CHUNKS;
const LARGE_MID_CHUNK0 = LARGE_CHUNKS_PER_EDGE / 2;

const smallCase = (name, kind, subdiv) => ({
  name,
  kind,
  subdiv,
  size: SMALL_SIZE,
  cx0: 0,
  cy0: 0,
  chunks: SMALL_CHUNKS_PER_EDGE,
});

const largeCase = (name, kind, subdiv, chunk0) => ({
  name,
  kind,
  subdiv,
  size: LARGE_SIZE,
  cx0: chunk0,
  cy0: chunk0,
  chunks: WINDOW_CHUNKS,
});

const CASES = [
  smallCase('mixed 64 near', 'mixed', SUBDIV_NEAR),
  smallCase('negative 64 near', 'negative', SUBDIV_NEAR),
  smallCase('ramp 64 near', 'ramp', SUBDIV_NEAR),
  smallCase('mixed 64 far', 'mixed', SUBDIV_FAR),
  smallCase('negative 64 far', 'negative', SUBDIV_FAR),
  largeCase('mixed 2048 corner near', 'mixed', SUBDIV_NEAR, LARGE_CORNER_CHUNK0),
  largeCase('mixed 2048 corner far', 'mixed', SUBDIV_FAR, LARGE_CORNER_CHUNK0),
  largeCase('negative 2048 corner near', 'negative', SUBDIV_NEAR, LARGE_CORNER_CHUNK0),
  largeCase('mixed 2048 mid near', 'mixed', SUBDIV_NEAR, LARGE_MID_CHUNK0),
  largeCase('mixed 2048 mid far', 'mixed', SUBDIV_FAR, LARGE_MID_CHUNK0),
  largeCase('mixed 2048 origin far', 'mixed', SUBDIV_FAR, 0),
];

/** Deformations of the shipped material that must move the drawn surface. */
const MUTANTS = [
  { key: 'shiftSubcell', caseName: 'mixed 64 near' },
  { key: 'shiftSubcell', caseName: 'mixed 64 far' },
  { key: 'dropHalfCell', caseName: 'mixed 64 far' },
  { key: 'truncDiv', caseName: 'negative 64 near' },
];

/** Known slack: at subdivision 4 the half-subcell offset never crosses a lattice edge. */
const SLACK_MUTANTS = [{ key: 'dropHalfCell', caseName: 'mixed 64 near' }];

const caseByName = (name) => {
  const found = CASES.find((c) => c.name === name);
  if (found === undefined) throw new Error(`no case named ${name}`);
  return found;
};

const JOBS = [
  ...CASES.map((c) => ({ ...c, label: c.name, mutate: null, slack: false })),
  ...[...MUTANTS, ...SLACK_MUTANTS].map((m) => ({
    ...caseByName(m.caseName),
    label: `mutant ${m.key} / ${m.caseName}`,
    mutate: m.key,
    slack: SLACK_MUTANTS.some((s) => s.key === m.key && s.caseName === m.caseName),
  })),
];

const mapCache = new Map();
function mapFor(kind, size) {
  const key = `${kind}:${size}`;
  let cells = mapCache.get(key);
  if (cells === undefined) {
    cells = buildMapCells(kind, size, REF_MIN_HEIGHT, REF_MAX_HEIGHT, REF_BAND_HEIGHT);
    mapCache.set(key, cells);
  }
  return cells;
}

const sideOf = (job) => job.chunks * REF_CHUNK_SIZE * job.subdiv;

function sampleCellCoord(chunk0, pixel, subdiv) {
  return chunk0 * REF_CHUNK_SIZE + (pixel + 0.5) / subdiv;
}

function expectedForCase(testCase, floorDiv) {
  const cells = mapFor(testCase.kind, testCase.size);
  const side = sideOf(testCase);
  const out = new Int32Array(side * side);
  for (let py = 0; py < side; py++) {
    const y = sampleCellCoord(testCase.cy0, py, testCase.subdiv);
    for (let px = 0; px < side; px++) {
      const x = sampleCellCoord(testCase.cx0, px, testCase.subdiv);
      out[py * side + px] = refSurfaceHeight(cells, testCase.size, x, y, floorDiv);
    }
  }
  return out;
}

