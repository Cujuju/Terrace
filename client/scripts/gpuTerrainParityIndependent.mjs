const OFF_MAP_COORDS = [-9, -0.1, 0, SMALL_SIZE - 0.001, SMALL_SIZE, SMALL_SIZE + 0.3, SMALL_SIZE + 40];

async function checkReferenceAgainstShipped() {
  const shared = await import('../../shared/src/drawnGround.ts');
  const grid = await import('../../shared/src/grid.ts');
  const constants = await import('../../shared/src/constants.ts');
  const drift = [];
  for (const [name, value] of [
    ['TERRAIN_LOD_NEAR_N', REF_LATTICE_N],
    ['TERRAIN_LOD_FAR_N', SUBDIV_FAR],
    ['BAND_HEIGHT', REF_BAND_HEIGHT],
    ['CHUNK_SIZE', REF_CHUNK_SIZE],
    ['MIN_HEIGHT', REF_MIN_HEIGHT],
    ['MAX_HEIGHT', REF_MAX_HEIGHT],
  ]) {
    if (constants[name] !== value) drift.push(`${name}: shipped ${constants[name]}, mine ${value}`);
  }
  let samples = 0;
  let mismatches = 0;
  let worst = null;
  let offMapMismatches = 0;
  for (const kind of ['mixed', 'negative', 'ramp']) {
    const cells = mapFor(kind, SMALL_SIZE);
    const map = grid.createHeightmap(SMALL_SIZE);
    map.cells.set(cells);
    for (const subdiv of [SUBDIV_NEAR, SUBDIV_FAR]) {
      const side = SMALL_SIZE * subdiv;
      for (let py = 0; py < side; py++) {
        const y = sampleCellCoord(0, py, subdiv);
        for (let px = 0; px < side; px++) {
          const x = sampleCellCoord(0, px, subdiv);
          samples++;
          if (refSurfaceHeight(cells, SMALL_SIZE, x, y) === shared.drawnGroundHeight(map, x, y)) continue;
          mismatches++;
          if (worst === null) worst = { kind, subdiv, x, y };
        }
      }
    }
    for (const x of OFF_MAP_COORDS) {
      for (const y of OFF_MAP_COORDS) {
        samples++;
        if (refSurfaceHeight(cells, SMALL_SIZE, x, y) === shared.drawnGroundHeight(map, x, y)) continue;
        mismatches++;
        offMapMismatches++;
        if (worst === null) worst = { kind, subdiv: 'off-map', x, y };
      }
    }
  }
  return { drift, samples, mismatches, worst, offMapMismatches };
}

function referenceSelfTest() {
  const testCase = caseByName('negative 64 near');
  const good = expectedForCase(testCase);
  const bad = expectedForCase(testCase, truncDiv);
  let differing = 0;
  for (let i = 0; i < good.length; i++) if (good[i] !== bad[i]) differing++;
  return { samples: good.length, differing };
}

// ---------------------------------------------------------------------------

async function main() {
  const wanted = process.argv.slice(2).filter((a) => a in BROWSERS);
  const browsers = wanted.length > 0 ? wanted : ['swiftshader', 'real'];

  const ref = await checkReferenceAgainstShipped();
  console.log(
    `reference vs shipped drawnGroundHeight: ${ref.samples} samples, ${ref.mismatches} mismatches` +
      ` (${ref.offMapMismatches} of them off-map)`,
  );
  if (ref.drift.length > 0) console.log(`constant drift: ${ref.drift.join('; ')}`);
  if (ref.worst !== null) console.log(`first reference mismatch: ${JSON.stringify(ref.worst)}`);
  console.log('layered columns: refused (probe maps carry no columnSpans; unlayered reference only)');

  const self = referenceSelfTest();
  console.log(
    `reference self-test (trunc instead of floor): ${self.differing}/${self.samples} differ` +
      `${self.differing === 0 ? '  *** VACUOUS ***' : ''}`,
  );

  const runs = [];
  for (const which of browsers) {
    const dir = mkdtempSync(join(tmpdir(), 'gpu-parity-indep-page-'));
    let server;
    try {
      const inbox = createInbox();
      ({ server } = await startVite(dir, inbox));
      const port = server.config.server.port ?? server.httpServer.address().port;
      runs.push(await runBrowser(which, port, inbox));
    } catch (error) {
      console.log(`[${which}] SKIPPED: ${error.message}`);
    } finally {
      if (server !== undefined) await server.close().catch(() => {});
      rmSync(dir, { recursive: true, force: true });
    }
  }

  let total = 0;
  let failures = 0;
  for (const run of runs) {
    for (const r of run.results) {
      if (r.job.mutate === null) {
        total += r.samples;
        failures += r.mismatches + r.uncovered;
        if (r.mismatches > 0) {
          const side = sideOf(r.job);
          const wx = r.worst.index % side;
          const wy = (r.worst.index - wx) / side;
          console.log(
            `worst [${run.which}] ${r.job.label}: cell coord (` +
              `${sampleCellCoord(r.job.cx0, wx, r.job.subdiv)}, ` +
              `${sampleCellCoord(r.job.cy0, wy, r.job.subdiv)}) ` +
              `gpu ${r.worst.gpu} expected ${r.worst.expected} delta ${r.worst.delta}`,
          );
        }
      } else if (!r.job.slack && r.mismatches === 0) {
        console.log(`[${run.which}] *** ${r.job.label} undetected; this check is vacuous ***`);
        failures++;
      }
    }
    if (run.errors.length > 0) console.log(`[${run.which}] page errors: ${run.errors.join(' | ')}`);
  }

  if (runs.length > 1) {
    let disagree = 0;
    for (let i = 0; i < runs[0].results.length; i++) {
      if (runs[0].results[i].mismatches !== runs[1].results[i].mismatches) disagree++;
    }
    console.log(`\n${runs[0].which} and ${runs[1].which} agree on every job: ${disagree === 0 ? 'yes' : `no (${disagree} differ)`}`);
  }

  console.log(`\nbrowsers run ${runs.length}, total samples ${total}, failures ${failures}`);
  const ok = runs.length > 0 && failures === 0 && ref.mismatches === 0 && self.differing > 0;
  console.log(ok ? 'PASS' : 'FAIL');
  process.exit(ok ? 0 : 1);
}

await main();
