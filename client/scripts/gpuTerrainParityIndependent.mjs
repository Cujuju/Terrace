const MAP_LCG_MULTIPLIER = 1103515245;
const MAP_LCG_INCREMENT = 12345;
const MAP_LCG_MODULUS = 2 ** 31;
const MAP_SEED_MIX = 2654435761;
const RAMP_X_STRIDE = 7;
const RAMP_Y_STRIDE = 13;

function buildMapCells(kind, size, minHeight, maxHeight, bandHeight) {
  const cells = new Int16Array(size * size);
  let state = (size * MAP_SEED_MIX) % MAP_LCG_MODULUS;
  for (let i = 0; i < cells.length; i++) {
    state = (state * MAP_LCG_MULTIPLIER + MAP_LCG_INCREMENT) % MAP_LCG_MODULUS;
    if (kind === 'ramp') {
      const x = i % size;
      const y = (i - x) / size;
      const stride = (x * RAMP_X_STRIDE + y * RAMP_Y_STRIDE) * bandHeight;
      cells[i] = minHeight + (stride % (maxHeight - minHeight + 1));
    } else if (kind === 'negative') {
      cells[i] = minHeight + (state % (-bandHeight - minHeight + 1));
    } else {
      cells[i] = minHeight + (state % (maxHeight - minHeight + 1));
    }
  }
  return cells;
}

const MAP_BUILDER_SOURCE = `${buildMapCells.toString()}
const MAP_LCG_MULTIPLIER = ${MAP_LCG_MULTIPLIER};
const MAP_LCG_INCREMENT = ${MAP_LCG_INCREMENT};
const MAP_LCG_MODULUS = ${MAP_LCG_MODULUS};
const MAP_SEED_MIX = ${MAP_SEED_MIX};
const RAMP_X_STRIDE = ${RAMP_X_STRIDE};
const RAMP_Y_STRIDE = ${RAMP_Y_STRIDE};`;

