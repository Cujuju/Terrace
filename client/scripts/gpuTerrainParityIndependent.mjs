// Second opinion on GPU/TS terrain parity, built to disagree with
// client/scripts/gpuTerrainParity.mjs wherever it can.
//
//   expected  an integer reference written from the spec, not drawnGroundHeight
//   measured  the real gpuTerrainMaterial rasterised top-down, one pixel per
//             subcell, vertex-stage height read back through a float target
//   driven    by the page posting results back, not by CDP evaluate
//
// Mutants deform the shipped material and must be caught, so a pass is not
// vacuous. Layered columns are refused rather than silently compared.
