function readBody(req) {
  return new Promise((res, rej) => {
    const chunks = [];
    req.on('data', (c) => chunks.push(c));
    req.on('end', () => res(Buffer.concat(chunks)));
    req.on('error', rej);
  });
}

function wslHostIp() {
  const out = execFileSync('ip', ['-o', '-4', 'addr', 'show', 'eth0'], { encoding: 'utf8' });
  const match = /inet (\d+\.\d+\.\d+\.\d+)/.exec(out);
  if (match === null) throw new Error('no IPv4 address on eth0');
  return match[1];
}

async function startVite(scratch, inbox) {
  writeFileSync(join(scratch, 'index.html'), PROBE_PAGE);
  writeFileSync(join(scratch, 'probe.js'), PROBE_SCRIPT);
  const server = await createViteServer({
    configFile: false,
    root: scratch,
    logLevel: 'error',
    appType: 'mpa',
    optimizeDeps: { noDiscovery: true, include: [] },
    plugins: [
      {
        name: 'probe-inbox',
        configureServer(dev) {
          dev.middlewares.use(META_ROUTE, (req, res) => {
            readBody(req).then((body) => {
              inbox.resolveMeta(JSON.parse(body.toString('utf8')));
              res.end('ok');
            });
          });
          dev.middlewares.use(HEIGHTS_ROUTE, (req, res) => {
            readBody(req).then((body) => {
              inbox.resolveHeights(
                new Float32Array(
                  body.buffer.slice(body.byteOffset, body.byteOffset + body.byteLength),
                ),
              );
              res.end('ok');
            });
          });
        },
      },
    ],
    resolve: {
      alias: {
        three: join(CLIENT_ROOT, 'node_modules/three/build/three.module.js'),
        '@terrace/shared': join(REPO_ROOT, 'shared/src/index.ts'),
        gpuTerrainMaterial: join(CLIENT_ROOT, 'src/render/gpuTerrainMaterial.ts'),
        gpuTerrainTextures: join(CLIENT_ROOT, 'src/render/gpuTerrainTextures.ts'),
      },
    },
    server: { port: 0, strictPort: false, host: true, allowedHosts: true, fs: { allow: [REPO_ROOT] } },
  });
  await server.listen();
  return { server, port: server.config.server.port ?? server.httpServer.address().port };
}

