const REF_LATTICE_N = 4;
const REF_SUBCELL_DENOM = 2 * REF_LATTICE_N;
const REF_BAND_HEIGHT = 16;
const REF_BAND_BLEND_DENOM = REF_SUBCELL_DENOM * REF_SUBCELL_DENOM * REF_BAND_HEIGHT;
const REF_CHUNK_SIZE = 16;
const REF_MIN_HEIGHT = -1536;
const REF_MAX_HEIGHT = 1024;
const REF_CELL_WORLD_SIZE = 1 / 4;
const REF_CELL_CENTRE_OFFSET = 0.5;

const SUBDIV_NEAR = 4;
const SUBDIV_FAR = 1;

function refFloorDiv(a, b) {
  const q = Math.floor(a / b);
  return q * b > a ? q - 1 : q;
}

function refClampCoord(size, coord) {
  return coord > 0 ? (coord < size ? coord : size) : 0;
}

function refClampCell(size, i) {
  return i < 0 ? 0 : i > size - 1 ? size - 1 : i;
}

function refAxis(size, coord) {
  const c = refClampCoord(size, coord);
  const q = 2 * Math.floor(c * REF_LATTICE_N) + 1 - REF_LATTICE_N;
  const base = refFloorDiv(q, REF_SUBCELL_DENOM);
  return {
    i0: refClampCell(size, base),
    i1: refClampCell(size, base + 1),
    f: q - base * REF_SUBCELL_DENOM,
  };
}

function refSurfaceHeight(cells, size, x, y, floorDiv = refFloorDiv) {
  const ax = refAxis(size, x);
  const ay = refAxis(size, y);
  const d = REF_SUBCELL_DENOM;
  const numerator =
    (d - ax.f) * (d - ay.f) * cells[ay.i0 * size + ax.i0] +
    ax.f * (d - ay.f) * cells[ay.i0 * size + ax.i1] +
    (d - ax.f) * ay.f * cells[ay.i1 * size + ax.i0] +
    ax.f * ay.f * cells[ay.i1 * size + ax.i1];
  return floorDiv(numerator, REF_BAND_BLEND_DENOM) * REF_BAND_HEIGHT;
}

/** Deliberately wrong: truncates toward zero, the classic negative-height trap. */
function truncDiv(a, b) {
  return Math.trunc(a / b);
}

