function startChrome(spec, url) {
  const port = CDP_PORT_BASE + Math.floor(Math.random() * CDP_PORT_SPREAD);
  const stamp = `${process.pid}-${port}`;
  const profileWsl = spec.windows
    ? join(WINDOWS_TEMP_WSL_PATH, WINDOWS_PROFILE_PREFIX + stamp)
    : mkdtempSync(join(tmpdir(), 'gpu-parity-indep-'));
  if (spec.windows) mkdirSync(profileWsl, { recursive: true });
  const profileArg = spec.windows
    ? `${WINDOWS_TEMP_DOS_PATH}\\${WINDOWS_PROFILE_PREFIX}${stamp}`
    : profileWsl;
  const child = spawn(
    spec.binary,
    [
      '--no-sandbox',
      '--disable-dev-shm-usage',
      '--no-first-run',
      '--no-default-browser-check',
      '--headless=new',
      ...spec.args,
      `--user-data-dir=${profileArg}`,
      `--remote-debugging-port=${port}`,
      url,
    ],
    { stdio: ['ignore', 'ignore', 'pipe'] },
  );
  const stderr = [];
  child.stderr.on('data', (c) => stderr.push(c.toString()));
  const cleanup = () => {
    try {
      child.kill('SIGKILL');
    } catch {}
    try {
      rmSync(profileWsl, { recursive: true, force: true });
    } catch {}
  };
  process.on('exit', cleanup);
  return { child, cleanup, stderr, port };
}

function compare(gpu, expected) {
  let mismatches = 0;
  let worst = null;
  for (let i = 0; i < expected.length; i++) {
    if (gpu[i] === expected[i]) continue;
    mismatches++;
    const delta = Math.abs(gpu[i] - expected[i]);
    if (worst === null || delta > worst.delta) {
      worst = { index: i, gpu: gpu[i], expected: expected[i], delta };
    }
  }
  return { samples: expected.length, mismatches, worst };
}

async function runBrowser(which, port, inbox) {
  const spec = BROWSERS[which]();
  const host = spec.windows ? wslHostIp() : '127.0.0.1';
  const chrome = startChrome(spec, `http://${host}:${port}/`);

  const timeout = new Promise((_, rej) =>
    setTimeout(() => rej(new Error(`no results within ${RUN_TIMEOUT_MS}ms`)), RUN_TIMEOUT_MS),
  );
  let meta;
  let heights;
  try {
    meta = await Promise.race([inbox.meta, timeout]);
    heights = await Promise.race([inbox.heights, timeout]);
  } catch (error) {
    chrome.cleanup();
    throw new Error(`${error.message}; chrome stderr: ${chrome.stderr.join('').slice(-400)}`);
  }
  chrome.cleanup();

  if (meta.fatal !== null) throw new Error(`page failed: ${meta.fatal}`);
  console.log(`[${which}] renderer: ${meta.renderer}`);

  const results = [];
  let offset = 0;
  for (let i = 0; i < JOBS.length; i++) {
    const job = JOBS[i];
    const reported = meta.jobs[i];
    if (reported === undefined || reported.label !== job.label) {
      throw new Error(`page returned ${meta.jobs.length} jobs for ${JOBS.length} requested`);
    }
    const count = reported.side * reported.side;
    const gpu = heights.subarray(offset, offset + count);
    offset += count;
    const cmp = compare(gpu, expectedForCase(job));
    results.push({ ...cmp, job, uncovered: reported.uncovered });
    console.log(
      `[${which}] ${job.label.padEnd(34)} samples ${String(cmp.samples).padStart(6)}` +
        `  mismatches ${String(cmp.mismatches).padStart(6)}  uncovered ${reported.uncovered}` +
        (job.mutate === null ? '' : job.slack ? '  (no-op by design)' : '  (must be non-zero)'),
    );
  }
  if (offset * FLOAT_BYTES !== heights.byteLength) {
    throw new Error(`payload was ${heights.byteLength} bytes, consumed ${offset * FLOAT_BYTES}`);
  }
  return { which, renderer: meta.renderer, results, errors: meta.errors };
}

